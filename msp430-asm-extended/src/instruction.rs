use std::fmt;

/// Container for all instruction types (MSP430 base + MSP430X extended)
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Instruction {
    // Base MSP430 single operand instructions
    Rrc(Rrc),
    Swpb(Swpb),
    Rra(Rra),
    Sxt(Sxt),
    Push(Push),
    Call(Call),
    Reti(Reti),

    // Base MSP430 jump instructions
    Jnz(Jnz),
    Jz(Jz),
    Jlo(Jlo),
    Jc(Jc),
    Jn(Jn),
    Jge(Jge),
    Jl(Jl),
    Jmp(Jmp),

    // Base MSP430 two operand instructions
    Mov(Mov),
    Add(Add),
    Addc(Addc),
    Subc(Subc),
    Sub(Sub),
    Cmp(Cmp),
    Dadd(Dadd),
    Bit(Bit),
    Bic(Bic),
    Bis(Bis),
    Xor(Xor),
    And(And),

    // Base MSP430 emulated instructions
    Adc(Adc),
    Br(Br),
    Clr(Clr),
    Clrc(Clrc),
    Clrn(Clrn),
    Clrz(Clrz),
    Dadc(Dadc),
    Dec(Dec),
    Decd(Decd),
    Dint(Dint),
    Eint(Eint),
    Inc(Inc),
    Incd(Incd),
    Inv(Inv),
    Nop(Nop),
    Pop(Pop),
    Ret(Ret),
    Rla(Rla),
    Rlc(Rlc),
    Sbc(Sbc),
    Setc(Setc),
    Setn(Setn),
    Setz(Setz),
    Tst(Tst),

    // MSP430X extended instructions
    Mova(AddressInstruction),
    Cmpa(AddressInstruction),
    Adda(AddressInstruction),
    Suba(AddressInstruction),
    Bra(Bra),
    Calla(Calla),
    Reta(Reta),
    Rrcm(RotateMultiple),
    Rram(RotateMultiple),
    Rlam(RotateMultiple),
    Rrum(RotateMultiple),
    Pushm(PushPopMultiple),
    Popm(PushPopMultiple),
}

impl Instruction {
    pub fn size(&self) -> usize {
        match self {
            // Base MSP430 instructions
            Self::Rrc(inst) => inst.size(),
            Self::Swpb(inst) => inst.size(),
            Self::Rra(inst) => inst.size(),
            Self::Sxt(inst) => inst.size(),
            Self::Push(inst) => inst.size(),
            Self::Call(inst) => inst.size(),
            Self::Reti(inst) => inst.size(),
            Self::Jnz(inst) => inst.size(),
            Self::Jz(inst) => inst.size(),
            Self::Jlo(inst) => inst.size(),
            Self::Jc(inst) => inst.size(),
            Self::Jn(inst) => inst.size(),
            Self::Jge(inst) => inst.size(),
            Self::Jl(inst) => inst.size(),
            Self::Jmp(inst) => inst.size(),
            Self::Mov(inst) => inst.size(),
            Self::Add(inst) => inst.size(),
            Self::Addc(inst) => inst.size(),
            Self::Subc(inst) => inst.size(),
            Self::Sub(inst) => inst.size(),
            Self::Cmp(inst) => inst.size(),
            Self::Dadd(inst) => inst.size(),
            Self::Bit(inst) => inst.size(),
            Self::Bic(inst) => inst.size(),
            Self::Bis(inst) => inst.size(),
            Self::Xor(inst) => inst.size(),
            Self::And(inst) => inst.size(),
            Self::Adc(inst) => inst.size(),
            Self::Br(inst) => inst.size(),
            Self::Clr(inst) => inst.size(),
            Self::Clrc(inst) => inst.size(),
            Self::Clrn(inst) => inst.size(),
            Self::Clrz(inst) => inst.size(),
            Self::Dadc(inst) => inst.size(),
            Self::Dec(inst) => inst.size(),
            Self::Decd(inst) => inst.size(),
            Self::Dint(inst) => inst.size(),
            Self::Eint(inst) => inst.size(),
            Self::Inc(inst) => inst.size(),
            Self::Incd(inst) => inst.size(),
            Self::Inv(inst) => inst.size(),
            Self::Nop(inst) => inst.size(),
            Self::Pop(inst) => inst.size(),
            Self::Ret(inst) => inst.size(),
            Self::Rla(inst) => inst.size(),
            Self::Rlc(inst) => inst.size(),
            Self::Sbc(inst) => inst.size(),
            Self::Setc(inst) => inst.size(),
            Self::Setn(inst) => inst.size(),
            Self::Setz(inst) => inst.size(),
            Self::Tst(inst) => inst.size(),
            // MSP430X extended instructions
            Self::Mova(inst) => inst.size(),
            Self::Cmpa(inst) => inst.size(),
            Self::Adda(inst) => inst.size(),
            Self::Suba(inst) => inst.size(),
            Self::Bra(inst) => inst.size(),
            Self::Calla(inst) => inst.size(),
            Self::Reta(inst) => inst.size(),
            Self::Rrcm(inst) => inst.size(),
            Self::Rram(inst) => inst.size(),
            Self::Rlam(inst) => inst.size(),
            Self::Rrum(inst) => inst.size(),
            Self::Pushm(inst) => inst.size(),
            Self::Popm(inst) => inst.size(),
        }
    }
}

